create table if not exists public.estimate_requests (
  id bigint generated by default as identity primary key,
  reference_number varchar(80) unique,
  customer_name varchar(180) not null,
  phone varchar(40) not null default '',
  email varchar(254) not null default '',
  preferred_contact varchar(20) not null default 'phone' check (preferred_contact in ('phone','email','text')),
  vehicle_year varchar(4) not null default '',
  vehicle_make varchar(100) not null default '',
  vehicle_model varchar(120) not null default '',
  vin varchar(17) not null default '',
  pnc_number varchar(80) not null default '',
  service_type varchar(120) not null default '',
