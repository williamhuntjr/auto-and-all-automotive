-- Administrative data is server-only. The Vercel application connects with
-- DATABASE_URL; no browser receives database credentials.
alter table public.inventory_parts enable row level security;
alter table public.paint_formula_records enable row level security;
alter table public.estimate_requests enable row level security;
alter table public.contact_requests enable row level security;
alter table public.site_settings enable row level security;

grant all on public.inventory_parts to postgres;
grant all on public.paint_formula_records to postgres;
grant all on public.estimate_requests to postgres;
grant all on public.contact_requests to postgres;
grant all on public.site_settings to postgres;
grant usage, select on all sequences in schema public to postgres;

do $$
begin
  if exists (select 1 from pg_roles where rolname = 'anon') then
    execute 'revoke all on public.inventory_parts, public.paint_formula_records, public.estimate_requests, public.contact_requests, public.site_settings from anon';
  end if;
  if exists (select 1 from pg_roles where rolname = 'authenticated') then
    execute 'revoke all on public.inventory_parts, public.paint_formula_records, public.estimate_requests, public.contact_requests, public.site_settings from authenticated';
  end if;
  if exists (select 1 from pg_roles where rolname = 'service_role') then
    execute 'grant all on public.inventory_parts, public.paint_formula_records, public.estimate_requests, public.contact_requests, public.site_settings to service_role';
    execute 'grant usage, select on all sequences in schema public to service_role';
  end if;
end;
$$;

