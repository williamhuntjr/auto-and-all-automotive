-- Launch schema for Auto And All Automotive.
-- Safe to run after 0001_service_categories.sql.

create or replace function public.set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists service_categories_set_updated_at on public.service_categories;
create trigger service_categories_set_updated_at
before update on public.service_categories
for each row execute function public.set_updated_at();

create table if not exists public.inventory_parts (
  id bigint generated by default as identity primary key,
  sku varchar(120) not null unique,
  part_name varchar(240) not null,
  category varchar(160) not null default '',
  interchange_number varchar(160) not null default '',
  picture_display_number varchar(120) not null default '',
  donor_stock varchar(80) not null default '',
  vin varchar(17) not null default '',
  vehicle_year varchar(4) not null default '',
  make varchar(100) not null default '',
  model varchar(120) not null default '',
  trim varchar(120) not null default '',
  series varchar(120) not null default '',
  production_date varchar(7) not null default '',
  engine varchar(160) not null default '',
  drivetrain varchar(80) not null default '',
  transmission varchar(160) not null default '',
  body_style varchar(120) not null default '',
  vehicle_type varchar(120) not null default '',
  fuel_type varchar(80) not null default '',
  assembly_plant text not null default '',
  mileage integer,
  factory_color varchar(120) not null default '',
  oem_paint_code varchar(80) not null default '',
  custom_paint_code varchar(80) not null default '',
  paint_system varchar(120) not null default '',
  custom_paint_name varchar(160) not null default '',
  custom_color_number varchar(100) not null default '',
  additive_formula jsonb not null default '[]'::jsonb,
  paint_notes text not null default '',
  condition_rating smallint check (condition_rating between 1 and 10),
  shelf_location varchar(120) not null default '',
  quantity integer not null default 0 check (quantity >= 0),
  reorder_point integer not null default 0 check (reorder_point >= 0),
  unit_cost numeric(12,2) not null default 0 check (unit_cost >= 0),
  retail_price numeric(12,2) not null default 0 check (retail_price >= 0),
  package_weight_lb numeric(10,2),
  package_length_in numeric(10,2),
  package_width_in numeric(10,2),
  package_height_in numeric(10,2),
  photo_gallery jsonb not null default '[]'::jsonb,
  data_source text not null default 'Manual entry',
  status varchar(40) not null default 'In stock' check (status in ('In stock','Low stock','Out of stock','Reserved','Sold','Archived')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint inventory_parts_vin_format check (vin = '' or vin ~ '^[A-HJ-NPR-Z0-9]{17}$')
);

create index if not exists inventory_parts_donor_stock_idx on public.inventory_parts(donor_stock);
create index if not exists inventory_parts_vin_idx on public.inventory_parts(vin) where vin <> '';
create index if not exists inventory_parts_category_idx on public.inventory_parts(category);
create index if not exists inventory_parts_location_idx on public.inventory_parts(shelf_location);
create index if not exists inventory_parts_status_idx on public.inventory_parts(status);

drop trigger if exists inventory_parts_set_updated_at on public.inventory_parts;
create trigger inventory_parts_set_updated_at
before update on public.inventory_parts
for each row execute function public.set_updated_at();

