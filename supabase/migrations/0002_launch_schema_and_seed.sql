  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint estimate_contact_required check (phone <> '' or email <> ''),
  constraint estimate_vin_format check (vin = '' or vin ~ '^[A-HJ-NPR-Z0-9]{17}$')
